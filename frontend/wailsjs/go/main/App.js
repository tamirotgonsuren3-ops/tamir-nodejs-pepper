const API = '/api/rpc';
export async function call(method, ...args) {
  const res = await fetch(API, { method:'POST', headers:{'Content-Type':'application/json'}, body: JSON.stringify({ method, args }) });
  const json = await res.json();
  if (!res.ok || json.error) throw new Error(json.error || `RPC ${method} failed`);
  return json.result;
}
function make(m){ return (...args) => call(m, ...args); }
